import { MobileAds } from 'yandex-mobile-ads';

let initPromise: Promise<boolean> | null = null;

/**
 * Запускает рекламный SDK ОДИН раз и только когда это действительно нужно (когда на экране
 * появляется баннер, а это бывает лишь после входа и принятия согласия). Автозапуск SDK при
 * старте приложения отключён в манифесте (scripts/ci.js) — иначе он стартовал бы раньше
 * согласия пользователя.
 *
 * Персонализацию рекламы НЕ включаем: согласие, которое даёт пользователь, — на обработку
 * данных самим приложением, а не на персональные рекламные профили, и отдельного согласия мы
 * не спрашиваем. Поэтому объявления подбираются без привязки к личным данным (по контексту).
 * Геолокацию Приложение вообще не использует. Если позже захотите персонализацию, это
 * отдельное согласие в приложении + правка политики конфиденциальности.
 *
 * Реклама никогда не должна ронять приложение: любая ошибка просто означает «рекламы нет».
 */
export function initializeAds(): Promise<boolean> {
  if (!initPromise) {
    initPromise = (async () => {
      try {
        MobileAds.setUserConsent(false);
        MobileAds.setLocationConsent(false);
        MobileAds.setAgeRestrictedUser(false);
        await MobileAds.initialize();
        return true;
      } catch {
        return false;
      }
    })();
  }
  return initPromise;
}
